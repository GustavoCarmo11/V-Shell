/// Draws the official Material 3 Cookie4Sided (4) or Cookie6Sided (6) path.
pub fn cookie_canvas(size: f32, sides: usize, fill: Color) -> Canvas {
    let (start, segments): (&[f32; 2], &[[f32; 6]]) = if sides == 4 {
        (&COOKIE4_START, &COOKIE4)
    } else {
        (&COOKIE6_START, &COOKIE6)
    };

    let mut path = Path::new().move_to(start[0] * size, start[1] * size);

    for segment in segments {
        path = path.cubic_to(
            segment[0] * size,
            segment[1] * size,
            segment[2] * size,
            segment[3] * size,
            segment[4] * size,
            segment[5] * size,
        );
    }

    let path = path.close().fill(fill);

    Canvas::new()
        .width(size)
        .height(size)
        .shapes(vec![Box::new(path)])
}
